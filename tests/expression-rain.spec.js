import {test,expect} from '@playwright/test'

test('optional expression events drive the existing rain instance and return to manual', async ({page}) => {
  test.skip(!process.env.RAIN_AR_DEV_URL,'Requires Vite source modules')
  await page.goto(process.env.RAIN_AR_DEV_URL)
  await page.locator('#controls-toggle').click()
  const panel=page.locator('#visual-rain')
  await panel.locator(':scope > summary').click()
  const trigger=panel.locator('[data-effect-trigger]')
  const status=panel.locator('[data-effect-status]')
  const canvas=page.locator('#visual-rain-canvas')
  const emit=state=>page.evaluate(async state=>{
    const {expressions}=await import('/src/expression/panel.js')
    expressions.snapshot.timestamp=performance.now()
    expressions.transition(state,expressions.snapshot.timestamp)
  },state)
  await expect(trigger).toHaveValue('manual')
  await emit('SMILE')
  await expect(canvas).toBeHidden()
  await trigger.selectOption('expression')
  await expect(canvas).toBeVisible()
  await expect(status).toContainText('持续')
  await emit('LAUGH')
  await expect(status).toContainText('收束')
  await expect(status).toContainText('生成强度 0%')
  await emit('SMILE')
  await expect(status).toContainText('持续')
  await emit('NO_FACE')
  await expect(status).toContainText('生成强度 0%')
  await trigger.selectOption('manual')
  await panel.getByRole('button',{name:'停止',exact:true}).click()
  await expect(canvas).toBeHidden()
})
